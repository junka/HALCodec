#!/usr/bin/env python3
"""gen_vt_probe_streams.py — (re)write VideoToolbox/layers/vt_probe_streams.h from
the bitstreams in VideoToolbox/probes/.

The probe streams are what the vtbox capability query feeds its own decoder, so
they are data, not code: keep the bytes as files next to the command that made
them (probes/README.md) and let this script emit the C arrays. Re-run after
adding, cutting or replacing a file:

    tools/gen_vt_probe_streams.py

A file's array name is the file's stem with the first letter capitalised and
each '_' kept, plus the "Stream"/"StreamLen" suffixes, which is what the existing
names already read as (h264_420_8.bin -> kH264_420_8Stream).
"""
import pathlib
import sys

PROBES = pathlib.Path("VideoToolbox/probes")
HEADER = pathlib.Path("VideoToolbox/layers/vt_probe_streams.h")
BYTES_PER_LINE = 16


def array_name(stem: str) -> str:
    """h264_420_8.bin -> kH264_420_8Stream, the spelling the rows already read as."""
    parts = stem.split("_")
    return "k" + "_".join(p[:1].upper() + p[1:] for p in parts) + "Stream"


def render(stem: str, data: bytes) -> str:
    name = array_name(stem)
    out = [f"const unsigned char {name}[] = {{"]
    for i in range(0, len(data), BYTES_PER_LINE):
        chunk = data[i:i + BYTES_PER_LINE]
        out.append("    " + " ".join(f"0x{b:02x}," for b in chunk))
    out.append("};")
    out.append(f"const unsigned int {name}Len = {len(data)};")
    out.append("")
    return "\n".join(out)


def main() -> int:
    files = sorted(PROBES.glob("*.bin"))
    if not files:
        print(f"no probe streams under {PROBES}", file=sys.stderr)
        return 1
    body = "\n".join(render(f.stem, f.read_bytes()) for f in files)
    header = (
        "// vt_probe_streams.h -- embedded decode-probe streams for capability\n"
        "// introspection. GENERATED by tools/gen_vt_probe_streams.py from\n"
        "// VideoToolbox/probes/*.bin; edit those files (see probes/README.md for the\n"
        "// command that makes each), never this listing.\n"
        "//\n"
        "// Each is a complete elementary stream for one input class: parameter sets\n"
        "// plus one intra picture (or the codec's own equivalent -- see the row's\n"
        "// kind in vt_caps.cc). The probe decodes it and reads the pixel format of\n"
        "// what comes back, so the capability table states what the hardware\n"
        "// actually produces rather than what a session-creation call would admit.\n"
        "\n"
        "#ifndef VIDEOTOOLBOX_LAYERS_VT_PROBE_STREAMS_H\n"
        "#define VIDEOTOOLBOX_LAYERS_VT_PROBE_STREAMS_H\n"
        "\n"
        + body +
        "#endif  // VIDEOTOOLBOX_LAYERS_VT_PROBE_STREAMS_H\n"
    )
    HEADER.write_text(header)
    print(f"wrote {HEADER}: {len(files)} streams, "
          f"{sum(len(f.read_bytes()) for f in files)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
